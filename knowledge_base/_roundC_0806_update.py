def read(p):
    with io.open(p, encoding='utf-8') as f:
        return f.read()


def write(p, s):
    with io.open(p, 'w', encoding='utf-8', newline='\n') as f:
        f.write(s)


def bump(txt, newrefs):
    """更新 updated 日期 + 追加 cross_refs"""
    txt = re.sub(r'(?m)^updated:.*$', 'updated: ' + TODAY, txt, count=1)
    m = re.search(r'(?m)^cross_refs:(.*)$', txt)
    if m:
        line = m.group(0)
        add = [r for r in newrefs if r not in line]
        if add:
            txt = txt.replace(line, line + ', ' + ', '.join('[[%s]]' % r for r in add), 1)
    return txt


def append_section(txt, section):
    """在 '## 关联页面' 前插入新章节；若无则追加到末尾"""
    idx = txt.find('\n## 关联页面')
    if idx == -1:
        return txt.rstrip() + '\n\n' + section.strip() + '\n'
    return txt[:idx] + '\n\n' + section.strip() + '\n' + txt[idx:]


def add_backlink(txt, line):
    """在 '## 关联页面' / '## 关联知识' 区块尾部追加回链"""
    for head in ('## 关联页面（续）', '## 关联页面', '## 关联知识'):
        i = txt.find(head)
        if i == -1:
            continue
        j = txt.find('\n## ', i + len(head))
        seg_end = j if j != -1 else len(txt)
        if line.strip() in txt[i:seg_end]:
            return txt
        return txt[:seg_end].rstrip() + '\n' + line + '\n' + txt[seg_end:]
    return txt.rstrip() + '\n' + line + '\n'



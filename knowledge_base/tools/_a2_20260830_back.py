def bump(path: Path, brand: str) -> str:
    txt = path.read_text(encoding="utf-8")
    if f"近期动态刷新（{DATE}" in txt:
        return "skip(exists)"
    txt = re.sub(r"^updated:\s*\S+", f"updated: {DATE}", txt, count=1, flags=re.M)
    if brand in SRC_ADD:
        m = re.search(r"^sources:\s*\[(.*?)\]", txt, flags=re.M | re.S)
        if m and SRC_ADD[brand] not in m.group(1):
            inner = m.group(1).rstrip()
            txt = txt[: m.start()] + f"sources: [{inner}, {SRC_ADD[brand]}]" + txt[m.end():]
    if not txt.endswith("\n"):
        txt += "\n"
    txt += BLOCKS[brand]
    path.write_text(txt, encoding="utf-8")
    return "ok"


def backfill_superseded(fname: str, newpage: str, note: str) -> str:
    p = SRC / fname
    if not p.exists():
        return "MISSING"
    txt = p.read_text(encoding="utf-8")
    changed = []
    if "superseded_by:" not in txt:
        txt = re.sub(
            r"^(brand_specific:\s*\S+)$",
            "\\1\nsuperseded_by: \"[[" + newpage + "]]\"",
            txt,
            count=1,
            flags=re.M,
        )
        changed.append("superseded_by")
    if "## ⚠️ 数据矛盾" not in txt:
        if not txt.endswith("\n"):
            txt += "\n"
        txt += f"\n## ⚠️ 数据矛盾\n\n{note}\n"
        changed.append("contradiction")
    p.write_text(txt, encoding="utf-8")
    return ",".join(changed) or "nochange"


